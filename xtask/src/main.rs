//! cargo xtask layers   check the crate dependency layering (AGENTS.md §2)
//! cargo xtask parity   regenerate docs/parity-checklist.md from the menu catalog
//! cargo xtask ci       fmt --check, clippy -D warnings, test, layers (the pre-commit gate)

use std::collections::BTreeMap;
use std::process::{Command, ExitCode};

/// Layer of every workspace crate. A crate may depend only on strictly lower layers.
/// Register new crates here.
const LAYERS: &[(&str, u8)] = &[
    ("dbcraft-core", 0),
    ("dbcraft-sql", 0),
    ("dbcraft-model", 1),
    ("dbcraft-drivers", 2),
    ("dbcraft-engine", 3),
    ("dbcraft-ui-egui", 4),
    ("dbcraft-automation", 4),
    ("dbcraft", 5),
    ("dbcraft-cli", 5),
    ("xtask", 6),
];

/// Crates that must stay free of workspace dependencies.
const STANDALONE: &[&str] = &["dbcraft-sql"];
/// GUI crates allowed only at the UI layer and above.
const GUI_DEPS: &[&str] = &["egui", "eframe", "egui_extras", "egui-phosphor", "egui_kittest", "rfd", "winit"];
const GUI_MIN_LAYER: u8 = 4;

fn main() -> ExitCode {
    let task = std::env::args().nth(1).unwrap_or_default();
    let ok = match task.as_str() {
        "layers" => layers(),
        "parity" => parity(),
        "ci" => ci(),
        _ => {
            eprintln!("usage: cargo xtask <layers|parity|ci>");
            false
        }
    };
    if ok { ExitCode::SUCCESS } else { ExitCode::FAILURE }
}

fn layers() -> bool {
    let out = match Command::new(env!("CARGO")).args(["metadata", "--format-version", "1", "--no-deps"]).output() {
        Ok(o) if o.status.success() => o.stdout,
        Ok(o) => {
            eprintln!("cargo metadata failed: {}", String::from_utf8_lossy(&o.stderr));
            return false;
        }
        Err(e) => {
            eprintln!("cannot run cargo: {e}");
            return false;
        }
    };
    let meta: serde_json::Value = match serde_json::from_slice(&out) {
        Ok(m) => m,
        Err(e) => {
            eprintln!("bad cargo metadata: {e}");
            return false;
        }
    };
    let layer: BTreeMap<&str, u8> = LAYERS.iter().copied().collect();
    let mut errors = Vec::new();
    for pkg in meta["packages"].as_array().into_iter().flatten() {
        let name = pkg["name"].as_str().unwrap_or("");
        let Some(&my) = layer.get(name) else {
            errors.push(format!("{name}: not registered in xtask/src/main.rs LAYERS"));
            continue;
        };
        for dep in pkg["dependencies"].as_array().into_iter().flatten() {
            if dep["kind"].as_str().is_some() {
                continue; // dev/build deps are free
            }
            let d = dep["name"].as_str().unwrap_or("");
            if let Some(&theirs) = layer.get(d) {
                if STANDALONE.contains(&name) {
                    errors.push(format!("{name} must be standalone but depends on {d}"));
                } else if theirs >= my {
                    errors.push(format!("{name} (L{my}) depends on {d} (L{theirs}): only lower layers allowed"));
                }
            }
            if GUI_DEPS.contains(&d) && my < GUI_MIN_LAYER {
                errors.push(format!("{name} (L{my}) depends on GUI crate {d}: only L{GUI_MIN_LAYER}+ may"));
            }
        }
    }
    if errors.is_empty() {
        println!("layers: ok");
        true
    } else {
        errors.iter().for_each(|e| eprintln!("layers: {e}"));
        false
    }
}

fn parity() -> bool {
    let engine: Vec<&str> = dbcraft_engine_ids();
    let mut md = String::from("# Menu parity checklist\n\nGenerated by `cargo xtask parity` from `crates/ui-egui/src/menu_catalog.rs`. Do not edit.\n\n");
    let (live, total) = dbcraft_ui_egui::parity();
    md.push_str(&format!("**{live} / {total} menu items live.** Wiring only, not behaviour depth: see `ROADMAP.md`.\n"));
    let mut current = "";
    for item in dbcraft_ui_egui::menu_catalog::CATALOG {
        let menu = item.path.split('/').next().unwrap_or("");
        if menu != current {
            md.push_str(&format!("\n## {menu}\n\n"));
            current = menu;
        }
        let is_live = engine.contains(&item.id) || dbcraft_ui_egui::UI_COMMANDS.contains(&item.id);
        md.push_str(&format!("- [{}] {} (`{}`)\n", if is_live { "x" } else { " " }, item.path, item.id));
    }
    match std::fs::write("docs/parity-checklist.md", md) {
        Ok(()) => {
            println!("parity: {live}/{total} -> docs/parity-checklist.md");
            true
        }
        Err(e) => {
            eprintln!("parity: cannot write docs/parity-checklist.md: {e}");
            false
        }
    }
}

fn dbcraft_engine_ids() -> Vec<&'static str> {
    dbcraft_ui_egui::engine_command_ids()
}

fn ci() -> bool {
    let steps: &[&[&str]] = &[&["fmt", "--all", "--check"], &["clippy", "--workspace", "--all-targets", "--", "-D", "warnings"], &["test", "--workspace"]];
    for args in steps {
        println!("==> cargo {}", args.join(" "));
        match Command::new(env!("CARGO")).args(*args).status() {
            Ok(s) if s.success() => {}
            _ => {
                eprintln!("ci: `cargo {}` failed", args.join(" "));
                return false;
            }
        }
    }
    layers()
}
